function Lu = laplacian4_g(ug, grid)

uxx = ( ...
    -ug(grid.i1+2:grid.i2+2, grid.j1:grid.j2, grid.k1:grid.k2) ...
    +16*ug(grid.i1+1:grid.i2+1, grid.j1:grid.j2, grid.k1:grid.k2) ...
    -30*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1:grid.k2) ...
    +16*ug(grid.i1-1:grid.i2-1, grid.j1:grid.j2, grid.k1:grid.k2) ...
    -ug(grid.i1-2:grid.i2-2, grid.j1:grid.j2, grid.k1:grid.k2) ) / (12*grid.dx^2);

uyy = ( ...
    -ug(grid.i1:grid.i2, grid.j1+2:grid.j2+2, grid.k1:grid.k2) ...
    +16*ug(grid.i1:grid.i2, grid.j1+1:grid.j2+1, grid.k1:grid.k2) ...
    -30*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1:grid.k2) ...
    +16*ug(grid.i1:grid.i2, grid.j1-1:grid.j2-1, grid.k1:grid.k2) ...
    -ug(grid.i1:grid.i2, grid.j1-2:grid.j2-2, grid.k1:grid.k2) ) / (12*grid.dy^2);

uzz = ( ...
    -ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1+2:grid.k2+2) ...
    +16*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1+1:grid.k2+1) ...
    -30*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1:grid.k2) ...
    +16*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1-1:grid.k2-1) ...
    -ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1-2:grid.k2-2) ) / (12*grid.dz^2);

Lu = uxx + uyy + uzz;

end