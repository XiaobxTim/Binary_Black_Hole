function uz = ddz4_g(ug, grid)

uz = ( ...
    -ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1+2:grid.k2+2) ...
    +8*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1+1:grid.k2+1) ...
    -8*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1-1:grid.k2-1) ...
    +ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1-2:grid.k2-2) ) / (12*grid.dz);

end