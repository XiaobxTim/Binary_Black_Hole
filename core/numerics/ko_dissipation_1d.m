function D = ko_dissipation_1d(ug, h, grid, dim)

switch dim
    case 1
        D = ( ...
            ug(grid.i1-3:grid.i2-3, grid.j1:grid.j2, grid.k1:grid.k2) ...
          - 6*ug(grid.i1-2:grid.i2-2, grid.j1:grid.j2, grid.k1:grid.k2) ...
          +15*ug(grid.i1-1:grid.i2-1, grid.j1:grid.j2, grid.k1:grid.k2) ...
          -20*ug(grid.i1  :grid.i2  , grid.j1:grid.j2, grid.k1:grid.k2) ...
          +15*ug(grid.i1+1:grid.i2+1, grid.j1:grid.j2, grid.k1:grid.k2) ...
          - 6*ug(grid.i1+2:grid.i2+2, grid.j1:grid.j2, grid.k1:grid.k2) ...
          +    ug(grid.i1+3:grid.i2+3, grid.j1:grid.j2, grid.k1:grid.k2) ) / (64*h);

    case 2
        D = ( ...
            ug(grid.i1:grid.i2, grid.j1-3:grid.j2-3, grid.k1:grid.k2) ...
          - 6*ug(grid.i1:grid.i2, grid.j1-2:grid.j2-2, grid.k1:grid.k2) ...
          +15*ug(grid.i1:grid.i2, grid.j1-1:grid.j2-1, grid.k1:grid.k2) ...
          -20*ug(grid.i1:grid.i2, grid.j1  :grid.j2  , grid.k1:grid.k2) ...
          +15*ug(grid.i1:grid.i2, grid.j1+1:grid.j2+1, grid.k1:grid.k2) ...
          - 6*ug(grid.i1:grid.i2, grid.j1+2:grid.j2+2, grid.k1:grid.k2) ...
          +    ug(grid.i1:grid.i2, grid.j1+3:grid.j2+3, grid.k1:grid.k2) ) / (64*h);

    case 3
        D = ( ...
            ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1-3:grid.k2-3) ...
          - 6*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1-2:grid.k2-2) ...
          +15*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1-1:grid.k2-1) ...
          -20*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1  :grid.k2  ) ...
          +15*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1+1:grid.k2+1) ...
          - 6*ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1+2:grid.k2+2) ...
          +    ug(grid.i1:grid.i2, grid.j1:grid.j2, grid.k1+3:grid.k2+3) ) / (64*h);

    otherwise
        error('Invalid dim in ko_dissipation_1d');
end

end