function ux = ddx4_g(ug, grid)

ux = ( ...
    -ug(grid.i1+2:grid.i2+2, grid.j1:grid.j2, grid.k1:grid.k2) ...
    +8*ug(grid.i1+1:grid.i2+1, grid.j1:grid.j2, grid.k1:grid.k2) ...
    -8*ug(grid.i1-1:grid.i2-1, grid.j1:grid.j2, grid.k1:grid.k2) ...
    +ug(grid.i1-2:grid.i2-2, grid.j1:grid.j2, grid.k1:grid.k2) ) / (12*grid.dx);

end