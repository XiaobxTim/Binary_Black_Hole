function uy = ddy4_g(ug, grid)

uy = ( ...
    -ug(grid.i1:grid.i2, grid.j1+2:grid.j2+2, grid.k1:grid.k2) ...
    +8*ug(grid.i1:grid.i2, grid.j1+1:grid.j2+1, grid.k1:grid.k2) ...
    -8*ug(grid.i1:grid.i2, grid.j1-1:grid.j2-1, grid.k1:grid.k2) ...
    +ug(grid.i1:grid.i2, grid.j1-2:grid.j2-2, grid.k1:grid.k2) ) / (12*grid.dy);

end